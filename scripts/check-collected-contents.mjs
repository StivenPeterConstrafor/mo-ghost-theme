import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const data=JSON.parse(fs.readFileSync('assets/data/faith-received/collected-work-contents.json','utf8'));
const context={window:{},document:{currentScript:{dataset:{contents:'contents.json'}}},fetch:async()=>({ok:true,json:async()=>data})};
vm.createContext(context);vm.runInContext(fs.readFileSync('assets/js/faith-collected-contents.js','utf8'),context);const c=context.window.MOCollectedContents;await c.ready;
assert.equal(Object.keys(data.works).length,226);
assert.match(c.preview('suarez-opera-vol-1'),/On God, one and triune; on predestination/);
assert.match(c.disclosure('suarez-opera-vol-1'),/p=570#b570-0/);
assert.match(c.search('luther-wa-schriften-1'),/Heidelberg/);
assert.doesNotMatch(c.preview('luther-wa-schriften-18'),/Concluding Material/);
assert.match(c.disclosure('luther-wa-schriften-55-ii'),/not yet available/);
assert.equal(c.disclosure('unlisted-work'),'');
assert.match(c.preview('lightfoot-the-works-of-the-reverend-and-learned-john-l'),/harmony of the four Evangelists/);
assert.match(c.search('gennadius-scholarios-works-vol-2'),/procession of the Holy Spirit/);
const routes={URL,URLSearchParams};vm.createContext(routes);vm.runInContext(fs.readFileSync('assets/js/page/faith-port-links.js','utf8'),routes);
for(const path of ['/the-faith-received/','/the-faith-received/all-works/','/the-faith-received/library/'])assert.equal(routes.FRPortLinks.localURL(path,'http://localhost:2368'),'/the-faith-received/all-works/?collection=all');
assert.equal(routes.FRPortLinks.localURL('/the-faith-received/read/?w=book#b52%3A0183A-0','http://localhost:2368'),'/the-faith-received/read/?w=book#b52%3A0183A-0');
console.log('✓ Collected contents: 226 volumes, section links, search labels and catalogue return routes');
