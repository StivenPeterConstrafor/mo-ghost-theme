#!/usr/bin/env node
/*
 * Copies assets/data/faith-received/public-slugs.json into the block
 * between the PUBLIC-SLUGS markers in assets/js/lib/faith-public-slugs.js.
 * The JSON is the source of truth; the copy inside the lib exists because
 * the reader must settle its own address synchronously (see the lib).
 *
 *   node scripts/build-public-slugs.mjs          write the block
 *   node scripts/build-public-slugs.mjs --check  exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "assets/data/faith-received/public-slugs.json");
const LIB = path.join(root, "assets/js/lib/faith-public-slugs.js");
const data = JSON.parse(readFileSync(SRC, "utf8"));
const eebo = {}, other = {}, seen = new Set();
for (const [internal, pub] of Object.entries(data.works || {})) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(pub)) throw new Error(`public-slugs: ${internal} -> "${pub}" is not a slug`);
  if (/^(eebo|pld|pg|po)-\d+$/.test(pub)) throw new Error(`public-slugs: ${internal} -> ${pub} looks like a family id`);
  if (seen.has(pub)) throw new Error(`public-slugs: ${pub} is used twice`);
  if (data.works[pub]) throw new Error(`public-slugs: ${pub} is itself an internal slug`);
  seen.add(pub);
  const m = /^eebo-(\d+)$/.exec(internal);
  if (m) eebo[m[1]] = pub; else other[internal] = pub;
}
const block = "  /* PUBLIC-SLUGS:BEGIN — generated by scripts/build-public-slugs.mjs; do not edit */\n" +
  "  const EEBO = " + JSON.stringify(eebo) + ";\n" +
  "  const OTHER = " + JSON.stringify(other) + ";\n" +
  "  /* PUBLIC-SLUGS:END */";
const lib = readFileSync(LIB, "utf8");
const re = /  \/\* PUBLIC-SLUGS:BEGIN[\s\S]*?\/\* PUBLIC-SLUGS:END \*\//;
if (!re.test(lib)) throw new Error("public-slugs: markers not found in the lib");
const next = lib.replace(re, block);
if (process.argv.includes("--check")) {
  if (next !== lib) { console.error("public-slugs: the lib is stale — run node scripts/build-public-slugs.mjs"); process.exit(1); }
  console.log(`public-slugs: ${Object.keys(eebo).length + Object.keys(other).length} names, lib current`);
} else {
  writeFileSync(LIB, next);
  console.log(`public-slugs: wrote ${Object.keys(eebo).length + Object.keys(other).length} names`);
}
