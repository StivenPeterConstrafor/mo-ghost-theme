import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context = {window:{},document:{currentScript:{dataset:{shelves:'catalogue.json'}}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('assets/js/lib/faith-web-graph.js','utf8'),context);
const graph={cats:[],nodes:['selected','source-1','source-2','reader-1','reader-2','unrelated'].map(fk=>({fk,pos:99})),edges:[[0,1,30,2],[0,2,20,0],[3,0,50,1],[4,0,40,0],[1,3,70,0],[5,2,90,0]]};
const focused=context.window.MOFaithWebFocus(graph,'selected',1);
assert.equal(focused.nodes.length,3);
assert.deepEqual(Array.from(focused.nodes,n=>n.fk),['selected','reader-1','source-1']);
assert.deepEqual(Array.from(focused.edges,e=>Array.from(e)),[[1,0,50,1],[0,2,30,2]]);
assert.equal(focused.nodes[0].pos,99);
assert.equal(graph.nodes.length,6);
assert.equal(graph.edges.length,6);
assert.equal(context.window.MOFaithWebFocus(graph,'missing'),graph);
const shelves=JSON.parse(fs.readFileSync('assets/data/faith-received/web-author-shelves.json','utf8')).authors;
assert.equal(shelves['ausonius-of-bordeaux'].sh,'pl');
assert.equal(shelves['queen-of-the-franks-radegund'].sh,'pl');
assert.equal(shelves['archbishop-of-bulgaria-theophylact'].sh,'gf');
assert.equal(shelves['denis-p-tau'].sh,'rc');
console.log('✓ Web layouts: directed author focus, preserved totals, and catalogue shelf fallbacks');
